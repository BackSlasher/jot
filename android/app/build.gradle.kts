/** Environment variable first (CI), then Gradle property (-P / gradle.properties). */
fun config(name: String): String? =
    providers.environmentVariable(name).orNull?.takeIf { it.isNotBlank() }
        ?: providers.gradleProperty(name).orNull?.takeIf { it.isNotBlank() }

val jotVersionName: String = config("JOT_VERSION_NAME") ?: "0.1.0"
val jotVersionCode: Int = config("JOT_VERSION_CODE")?.toInt() ?: 1

// Release signing contract (used by CI): all four env vars, keystore path in JOT_KEYSTORE_FILE.
// Without JOT_KEYSTORE_FILE the release APK is left unsigned (never debug-signed).
val releaseKeystore: String? = providers.environmentVariable("JOT_KEYSTORE_FILE").orNull?.takeIf { it.isNotBlank() }

android {
    namespace = "net.backslasher.jot"
    compileSdk = 37

    defaultConfig {
        applicationId = "net.backslasher.jot"
        minSdk = 26
        targetSdk = 37
        versionCode = jotVersionCode
        versionName = jotVersionName
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = providers.environmentVariable("JOT_KEYSTORE_PASSWORD").orNull
                keyAlias = providers.environmentVariable("JOT_KEY_ALIAS").orNull
                keyPassword = providers.environmentVariable("JOT_KEY_PASSWORD").orNull
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            signingConfig = if (releaseKeystore != null) signingConfigs.getByName("release") else null
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
        }
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

